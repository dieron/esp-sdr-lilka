const char *font_glyph(char c) {
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    for (size_t i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); i++)
        if (glyphs[i].ch == c) return glyphs[i].rows;
    return NULL; /* space and anything unknown draw nothing */
}
